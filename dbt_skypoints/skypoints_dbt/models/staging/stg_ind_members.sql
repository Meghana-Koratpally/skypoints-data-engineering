
SELECT
    TRIM(ID) AS MEMBER_ID,

    TRIM(NAME) AS MEMBER_NAME,

    TRY_TO_DATE(TRIM(DOB), 'DD-MM-YYYY') AS DATE_OF_BIRTH,

    UPPER(TRIM(TIERCODE)) AS TIER_CODE,

    TRY_TO_DATE(TRIM(ENROLLMENTDATE), 'DD-MM-YYYY') AS ENROLLMENT_DATE,

    UPPER(TRIM(INDIVIDUAL_OR_CORPORATE)) AS MEMBER_TYPE,

    TRY_TO_DATE(TRIM(FLIGHTDATE), 'DD-MM-YYYY') AS FLIGHT_DATE,

    SOURCE_FILE,

    LOAD_TIMESTAMP

FROM {{ source('skypoints_bronze', 'IND_MEMBERS') }}
