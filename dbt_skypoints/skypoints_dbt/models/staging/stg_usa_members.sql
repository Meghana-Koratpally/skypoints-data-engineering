
SELECT
    TRIM(ID) AS MEMBER_ID,
    TRIM(NAME) AS MEMBER_NAME,
    UPPER(TRIM(TIERCODE)) AS TIER_CODE,
    TRY_TO_DATE(LPAD(TRIM(ENROLLMENTDATE), 8, '0'),'MMDDYYYY') AS ENROLLMENT_DATE,
    TRY_TO_DATE(LPAD(TRIM(FLIGHTDATE), 8, '0'),'MMDDYYYY') AS FLIGHT_DATE,
    SOURCE_FILE,
    LOAD_TIMESTAMP
FROM {{ source('skypoints_bronze', 'USA_MEMBERS') }}
