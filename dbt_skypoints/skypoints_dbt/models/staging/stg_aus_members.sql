
SELECT
    TRIM(UNIQUE_ID) AS MEMBER_ID,

    TRIM(MEMBER_NAME) AS MEMBER_NAME,

    UPPER(TRIM(TIER_TYPE)) AS TIER_CODE,

    TRY_TO_DATE(TRIM(DATE_OF_BIRTH)) AS DATE_OF_BIRTH,

    TRY_TO_DATE(TRIM(DATE_OF_ENROLLMENT)) AS ENROLLMENT_DATE,

    TRY_TO_DATE(TRIM(DATE_OF_FLIGHT)) AS FLIGHT_DATE,

    SOURCE_FILE,

    LOAD_TIMESTAMP

FROM {{ source('skypoints_bronze', 'AUS_MEMBERS') }}
